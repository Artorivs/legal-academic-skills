#!/usr/bin/env python3
"""Regenerate project-import/PROJECT_UPLOAD_BUNDLE.md from the canonical sources.

The bundle concatenates the project instructions, every skill (in SKILL_INDEX.md order,
with its bundled reference files), every template, and the quick prompts.

Standard library only.

Usage:
    python3 scripts/build_bundle.py          # rewrite the bundle
    python3 scripts/build_bundle.py --check  # exit 1 if the bundle is out of date
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "project-import" / "PROJECT_UPLOAD_BUNDLE.md"
SEP = "\n\n---\n\n"

INTRO = (
    "# Legal Academic Research and Writing: Project Upload Bundle\n\n"
    "This consolidated document is for AI Projects that accept uploaded reference files but do not "
    "natively discover Agent Skills. Add it to your project knowledge and place the companion "
    "`PROJECT_INSTRUCTIONS.md` in the project's instruction field where available. Workflows below are "
    "available on demand; do not run all of them automatically. Where a workflow mentions a script under "
    "`scripts/`, it is available only when the full repository is present; otherwise follow the manual "
    "instruction beside it.\n\n"
    "Generated by `scripts/build_bundle.py`; edit the sources, not this file."
)


def split_frontmatter(text: str) -> tuple[dict, str]:
    if not text.startswith("---\n"):
        return {}, text
    _, fm, body = text.split("---", 2)
    fields = {}
    for line in fm.splitlines():
        m = re.match(r"^([A-Za-z][\w-]*):\s*(.*)$", line)
        if m:
            fields[m.group(1)] = m.group(2).strip().strip("'\"")
    return fields, body.strip()


def skill_order() -> list[str]:
    index = (ROOT / "SKILL_INDEX.md").read_text(encoding="utf-8")
    return list(dict.fromkeys(re.findall(r"\(skills/([a-z0-9-]+)/SKILL\.md\)", index)))


def build() -> str:
    parts = [INTRO]
    instructions = (ROOT / "project-import" / "PROJECT_INSTRUCTIONS.md").read_text(encoding="utf-8").strip()
    parts.append("## Project-wide instructions\n\n" + instructions)
    for name in skill_order():
        skill_dir = ROOT / "skills" / name
        fields, body = split_frontmatter((skill_dir / "SKILL.md").read_text(encoding="utf-8"))
        section = f"## Workflow: {name}\n\n**Use when:** {fields.get('description', '')}\n\n{body}"
        for ref in sorted((skill_dir / "references").rglob("*.md")) if (skill_dir / "references").is_dir() else []:
            rel = ref.relative_to(skill_dir).as_posix()
            section += f"\n\n### Reference for {name}: `{rel}`\n\n" + ref.read_text(encoding="utf-8").strip()
        parts.append(section)
    for template in sorted((ROOT / "templates").glob("*.md")):
        parts.append(f"# Reference template: {template.stem}\n\n" + template.read_text(encoding="utf-8").strip())
    prompts = (ROOT / "project-import" / "QUICK_PROMPTS.md").read_text(encoding="utf-8").strip()
    parts.append("# Quick prompts\n\n" + prompts)
    return SEP.join(parts) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv[1:]:
        current = BUNDLE.read_text(encoding="utf-8") if BUNDLE.exists() else ""
        if current != text:
            print("PROJECT_UPLOAD_BUNDLE.md is out of date; run python3 scripts/build_bundle.py", file=sys.stderr)
            return 1
        print("Bundle is up to date.")
        return 0
    BUNDLE.write_text(text, encoding="utf-8")
    print(f"Wrote {BUNDLE.relative_to(ROOT)} ({len(text.split())} words).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
